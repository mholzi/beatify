class TestProviderIsAccepted:
    """The root cause of "Cannot start — No playlists selected".

    `_validate_provider` coerces anything not in its whitelist to the default
    provider. `ma_library` was missing, so the selection silently became
    Spotify BEFORE the playlist guard ran — the exemption never matched, the
    request 400'd in ~4ms, and nothing was logged because validation precedes
    every log line. The function's own docstring records the identical
    failure for Apple Music (#808).
    """

    def test_the_library_provider_is_whitelisted(self):
        from custom_components.beatify.server.game_views import _validate_provider

        assert _validate_provider("ma_library") == "ma_library"

    def test_unknown_providers_are_still_coerced(self):
        from custom_components.beatify.server.game_views import _validate_provider

        assert _validate_provider("napster") != "napster"

    def test_players_advertise_library_support(self):
        """The wizard greys out providers a speaker can't play; without this
        flag Crate Digger would be offered on speakers that cannot serve it."""
        assert '"supports_ma_library"' in src("services/media_player.py")


