"""Crate Digger — regression guards for bugs found on real hardware.

Every check here corresponds to a defect that shipped and was diagnosed on a
live Home Assistant with Music Assistant voice satellites, an Android TV and
an Echo. They are deliberately structural (they read the source) because the
behaviour they protect involves device timing that a unit test cannot
reproduce — the alternative to a source guard is no guard at all.

Where a bug IS reproducible in pure logic it is tested properly instead; see
test_library_generator.py and test_library_metadata.py.
"""

from __future__ import annotations

from pathlib import Path

import pytest

COMPONENT = Path(__file__).resolve().parents[2] / "custom_components" / "beatify"


def src(relative: str) -> str:
    return (COMPONENT / relative).read_text(encoding="utf-8")


class TestSettingsReachTheGameTheyWereSetFor:
    """The off-by-one family: settings applying one game late.

    A room freezes its parameters at creation, but the lobby's reset button
    creates the next room immediately — so anything changed afterwards missed
    its own game. Songs are regenerated by a pre-start hook; device, TTS and
    party lights are re-applied from a server-side Store.
    """

    def test_pre_start_hook_fires_from_start_round(self):
        """Not from the REST view: the websocket admin path bypasses it.

        Hooking the view fixed the bug for one start path and left it live on
        the other, which is how this bug survived a correct-looking fix.
        """
        code = src("game/state_lifecycle.py")
        assert "pre_start_hook" in code
        assert "self.pre_start_hook = None" in code, "must fire once per game"

    def test_library_games_install_the_hook(self):
        assert "pre_start_hook = _regen_library_songs" in src("server/game_views.py")

    def test_output_settings_are_persisted_and_re_applied(self):
        assert "async_save_game_output_settings" in src("server/library_views.py")
        assert "async_load_game_output_settings" in src("server/game_views.py")

    def test_reset_clears_the_persisted_output_settings(self):
        """Upstream's reset is installation-wide (#2036); ours must follow,
        or the pre-start re-apply would restore pre-reset settings."""
        assert "async_clear_game_output_settings" in src("server/game_views.py")

    def test_device_switch_drops_the_cached_media_service(self):
        """#2143 changed HOW it is dropped, not THAT it is dropped.

        The service must still go — it captures entity and platform at
        construction, so keeping it routes playback to the old device. But
        nulling the reference outright also dropped the old speaker's pre-game
        volume (#1516) and queue (#2143). `release_media_player_service`
        preserves those and then nulls. A bare `= None` here is the regression.
        """
        code = src("server/game_views.py")
        assert "release_media_player_service()" in code
        assert "_media_player_service = None" not in code

    def test_device_switch_supersedes_the_lobby_prewarm(self):
        """#1540 pre-warms the service with the entity chosen at CREATE; a
        pre-warm landing after a switch would reinstate the old speaker."""
        code = src("server/game_views.py")
        assert "_cancel_prewarm" in code and "schedule_media_player_prewarm" in code


