class TestImportHygiene:
    """Module names used via attribute access need a module-level import.

    A missing `import contextlib` — masked because an unrelated function had
    a local aliased import — killed an endpoint mid-handler and strangled
    three architecturally correct fixes across as many releases.
    """

    @pytest.mark.parametrize(
        ("path", "module"),
        [
            ("server/game_views.py", "contextlib"),
            ("server/library_views.py", "json"),
            ("game/state_auto_advance.py", "time"),
            ("game/state_tts.py", "time"),
        ],
    )
    def test_module_level_import_present_where_used(self, path, module):
        code = src(path)
        if f"{module}." not in code:
            pytest.skip(f"{module} not used in {path}")
        assert any(line.strip() == f"import {module}" for line in code.splitlines()), (
            f"{path} uses {module}. without a module-level import"
        )
